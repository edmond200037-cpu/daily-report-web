import { expect, test } from '@playwright/test';
import { readSettledContrast } from './helpers/contrast';
import { mkdir, writeFile } from 'node:fs/promises';

for (const colorScheme of ['light', 'dark'] as const) test(`左滑與刪除確認白字 AA 對比 ${colorScheme}`, async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme, reducedMotion: 'reduce' });
  await page.goto('/#daily');
  await page.evaluate(async () => {
    const statePath = '/src/app/state.ts', domainPath = '/src/domain/daily.ts', bridgePath = '/src/app/react-store.ts';
    const { appState } = await import(/* @vite-ignore */ statePath);
    const { createTrade } = await import(/* @vite-ignore */ domainPath);
    const { notifyReact } = await import(/* @vite-ignore */ bridgePath);
    appState.daily.report.tradeSections.push(createTrade('刪除對比', '測試廠商', 0));
    appState.daily.expandedId = null;
    notifyReact();
  });
  const row = page.locator('[data-trade]').first();
  await row.scrollIntoViewIfNeeded();
  const rect = (await row.boundingBox())!, x = rect.x + rect.width - 35;
  const touch = { pointerId: 7, pointerType: 'touch', isPrimary: true, button: 0, buttons: 1, clientY: rect.y + 25 };
  await row.dispatchEvent('pointerdown', { ...touch, clientX: x });
  for (const dx of [15, 35, 60, 90]) await row.dispatchEvent('pointermove', { ...touch, clientX: x - dx });
  await row.dispatchEvent('pointerup', { ...touch, buttons: 0, clientX: x - 90 });
  const swipe = row.getByRole('button', { name: '刪除', exact: true });
  await expect(swipe).toBeVisible();
  const swipeColor = await readSettledContrast(swipe);
  await info.attach('swipe-colors', { body: JSON.stringify(swipeColor, null, 2), contentType: 'application/json' });
  await mkdir('artifacts/danger-contrast', { recursive: true });
  await writeFile(`artifacts/danger-contrast/swipe-${colorScheme}.json`, JSON.stringify(swipeColor, null, 2));
  expect(swipeColor.opacity).toBe(1);
  expect(swipeColor.foreground).toEqual([255, 255, 255]);
  expect(swipeColor.ratio).toBeGreaterThanOrEqual(4.5);
  await page.goto('/#settings/water');
  await page.getByRole('button', { name: '新增井位', exact: true }).click();
  await page.getByRole('textbox', { name: /^井位名稱/ }).fill('對比井');
  await page.getByRole('button', { name: '儲存', exact: true }).click();
  await page.getByRole('button', { name: '編輯對比井', exact: true }).click();
  await page.getByRole('button', { name: '刪除井位', exact: true }).click();
  const dialog = page.getByRole('alertdialog');
  await expect(dialog).toContainText('不會刪除歷史讀值');
  const confirm = dialog.getByRole('button', { name: '確認', exact: true });
  const dialogColor = await readSettledContrast(confirm);
  expect(dialogColor.opacity).toBe(1);
  expect(dialogColor.foreground).toEqual([255, 255, 255]);
  expect(dialogColor.ratio).toBeGreaterThanOrEqual(4.5);
  await mkdir('artifacts/danger-contrast', { recursive: true });
  await writeFile(`artifacts/danger-contrast/${colorScheme}.json`, JSON.stringify({ colorScheme, swipe: swipeColor, alertDialog: dialogColor }, null, 2));
  await page.mouse.move(0, 0);
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
});
